function s(prompt, explanation, labels, answer_id) {
  return {
    type: "single",
    prompt,
    explanation,
    options: labels.map((label, i) => ({ id: "abcd"[i], label })),
    answer_id,
  };
}
function m(prompt, explanation, labels, answer_ids) {
  return {
    type: "multiple",
    prompt,
    explanation,
    options: labels.map((label, i) => ({ id: "abcd"[i], label })),
    answer_ids,
  };
}
function b(prompt, explanation, answer_bool) {
  return { type: "boolean", prompt, explanation, answer_bool };
}
function t(prompt, explanation, accepted) {
  return { type: "typed", prompt, explanation, accepted, placeholder: "Type your answer" };
}
function img(prompt, explanation, glyph, caption, labels, answer_id, glyphs) {
  return {
    type: "image",
    prompt,
    explanation,
    media: { kind: "flag", glyph, caption },
    options: labels.map((label, i) => ({
      id: "abcd"[i],
      label,
      ...(glyphs?.[i] ? { glyph: glyphs[i] } : {}),
    })),
    answer_id,
  };
}
