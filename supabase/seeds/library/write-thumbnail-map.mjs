import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { assembleLibrary } from "./assemble.mjs";

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "..",
  "..",
  "geoverze-main",
  "geoverze-public-main",
  "src",
  "features",
  "play",
  "data",
  "libraryQuizThumbnails.generated.ts",
);

const quizzes = assembleLibrary();
const entries = quizzes
  .map(
    (quiz) => `  "${quiz.id}": {
    src: \`\${QUIZ_COVER_BASE}/${quiz.thumbnailFile}\`,
    alt: "Cover photography for ${quiz.title.replaceAll('"', '\\"')}",
    objectPosition: "center 46%",
  }`,
  )
  .join(",\n");

const file = `/** Generated by supabase/seeds/library/write-thumbnail-map.mjs — do not edit by hand. */
const QUIZ_COVER_BASE = "/assets/quizzes";

export const LIBRARY_QUIZ_THUMBNAILS = {
${entries},
};
`;

writeFileSync(out, file, "utf8");
console.log(`Wrote ${out} (${quizzes.length} entries)`);
