function fileFor(prefix, title) {
  return `${prefix}-${slugify(title)}-quiz.jpg`;
}

export function uniqueThumbnailSpecs() {
  const specs = [];
  for (const cat of CATEGORIES) {
    const scenes = SCENES[cat.id];
    if (!scenes || scenes.length !== cat.titles.length) {
      throw new Error(`Scene count mismatch for ${cat.id}`);
    }
    cat.titles.forEach((title, i) => {
      const [sceneTitle, concept] = scenes[i];
      if (sceneTitle !== title) {
        throw new Error(`Title mismatch ${cat.id}[${i}]: ${sceneTitle} vs ${title}`);
      }
      specs.push({
        id: quizId(cat.prefix, title),
        title,
        categoryId: cat.id,
        prefix: cat.prefix,
        filename: fileFor(cat.prefix, title),
        concept,
        prompt: `${concept}. ${QUALITY}`,
        objectPosition: cat.id === "mountains" || cat.id === "oceans" ? "center 40%" : "center 45%",
      });
    });
  }
  return specs;
}

